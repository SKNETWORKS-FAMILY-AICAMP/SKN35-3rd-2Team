"""
이미지 입력(멀티모달) 노드의 설정값.

- 이 노드(src/graph/node/multimodal)만 쓰는 값을 한곳에 모았다. config.py, models.py는 건드리지 않는다.
- 모두 코드 상수다 (.env로 바꾸지 않는다). 값을 바꾸려면 이 파일을 고친다.
- 이미지 장수, 크기, 형식의 한도는 DB와 같은 값을 써야 하므로 여기에 두지 않고 src/const/db_config.py를 읽는다.
- 채팅 모델과 키는 src/const/models.py의 create_openai_model()이 정한 팀 공통 모델을 쓴다
  (이미지 입력을 지원하는 모델이어야 한다. 기본 gpt-4o-mini는 지원한다).
"""

# ---------------------------------------------------------------------------
# 2단계: 크기 줄이기 (resize_images.py)
# ---------------------------------------------------------------------------
# 긴 변이 이 값(픽셀)을 넘으면 이 값에 맞춰 줄인다. 넘지 않으면 그대로 둔다.
# 2048인 이유: OpenAI는 detail=high에서 긴 변이 2048을 넘는 이미지를 어차피 2048에 맞춰 줄여서 읽는다
#   (2026-10 실제 호출로 토큰 수가 이 규칙과 일치하는 것을 확인). 그래서 2048까지는 줄여도 잃는 것이 없고,
#   그보다 큰 이미지만 올리는 용량을 줄이려고 미리 줄인다.
# 더 작게(1600 등) 줄이면 글자가 뭉개진다: 2600x900 한글 스크린샷을 1600px로 줄였더니 "에러"를 "예러"로 읽고
#   주석 한 줄을 빠뜨렸고, 줄이지 않으면 둘 다 정확했다. 같은 이미지에서 토큰(타일 수)은 똑같이 8타일이라 아끼는 것도 없었다.
# 또 다른 시험(식별자 20개가 든 스크린샷): 1600px에서 20개 모두, 1024px에서 17개를 읽었다. 해상도가 낮을수록 정확도가 떨어진다.
RESIZE_MAX_EDGE = 2048
RESIZE_JPEG_QUALITY = 90                    # JPEG 이미지를 줄여서 다시 저장할 때의 품질

# ---------------------------------------------------------------------------
# 3단계: 모델에 보낼 형태 (encode_images.py)
# ---------------------------------------------------------------------------
#   high: 글자가 많은 스크린샷(코드, 터미널, 오류 화면)을 정확히 읽는다. 대신 이미지 한 장의 입력 토큰이 크다.
#   low : 토큰은 적게 들지만 작은 글자를 못 읽을 수 있어서 코드/오류 화면에는 권하지 않는다.
#   auto: 모델이 알아서 정한다.
IMAGE_DETAIL = "high"

# ---------------------------------------------------------------------------
# 4단계: 모델 호출 (read_images.py)
# ---------------------------------------------------------------------------
VISION_TEMPERATURE = 0.0                    # 옮겨 적기는 매번 같은 결과가 나와야 하므로 0
VISION_TIMEOUT_SECONDS = 90
VISION_MAX_OUTPUT_TOKENS = 2000             # 이미지 3장의 읽은 결과를 담기에 충분한 길이
QUESTION_MAX_CHARS = 2000                   # 이미지를 읽을 때 참고로 보여 주는 사용자 질문의 최대 글자 수

# ---------------------------------------------------------------------------
# 5단계: 결과 정리 (build_analysis.py) - 항목 제목은 프롬프트와 정리 단계가 같은 것을 쓴다
# ---------------------------------------------------------------------------
SECTION_HEADINGS = (
    "[화면 설명]",
    "[오류 메시지]",
    "[코드]",
    "[환경 정보]",
    "[읽기 불확실]",
)
EMPTY_SECTION_TEXT = "없음"

# ---------------------------------------------------------------------------
# 처리 중 사용자에게 남기는 안내 문구 (결과 맨 앞에 "※"로 붙는다)
# ---------------------------------------------------------------------------
NO_IMAGE_NOTICE = "(분석할 이미지가 없습니다)"
EMPTY_RESULT_NOTICE = "(이미지에서 읽은 내용이 없습니다)"
